const canvas = new Uint8Array(W * H * 3);
const fill = (x, y, w, h, [r, g, b]) => {
  for (let yy = Math.max(0, y); yy < Math.min(H, y + h); yy++) {
    for (let xx = Math.max(0, x); xx < Math.min(W, x + w); xx++) {
      const i = (yy * W + xx) * 3;
      canvas[i] = r; canvas[i + 1] = g; canvas[i + 2] = b;
    }
  }
};
const fillRect = fill;

function drawText(text, x, y, scale, color, spacing = 1) {
  let cx = x;
  for (const ch of text) {
    const glyph = GLYPHS[ch] || GLYPHS[" "];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 6; col++) {
        if (glyph[row][col] !== "#" && glyph[row][col] !== ".") continue;
        if (glyph[row][col] === "#") fillRect(cx + col * scale, y + row * scale, scale, scale, color);
      }
    }
    cx += (6 + spacing) * scale;
  }
  return cx - x;
}
const textWidth = (text, scale, spacing = 1) => text.length * (6 + spacing) * scale - spacing * scale;

// Background
fillRect(0, 0, W, H, BG);
// Hairline frame
fillRect(32, 32, W - 64, 1, HAIRLINE);
fillRect(32, H - 33, W - 64, 1, HAIRLINE);
fillRect(32, 32, 1, H - 64, HAIRLINE);
fillRect(W - 33, 32, 1, H - 64, HAIRLINE);

// Brand mark: gate ring (rust), drawn as pixels
const cx = 108, cy = 118, r = 34, inner = 22, t = 6;
for (let y = -r; y <= r; y++) {
  for (let x = -r; x <= r; x++) {
    const d = Math.hypot(x, y);
    if (d <= r && d >= inner) fillRect(cx + x, cy + y, 1, 1, ACCENT);
  }
}
fillRect(cx - 5, cy - 5, 10, 10, ACCENT);

// Wordmark
drawText("RECALLGUARD", 168, 96, 9, INK, 2);
drawText("For agents on Walrus Memory", 168, 168, 3, SECONDARY, 1);

// Tagline
drawText("Your agent remembers.", 84, 262, 6, INK, 2);
drawText("Checks whether it's still true.", 84, 336, 4, SECONDARY, 1);

// Footer line
fillRect(84, 470, 140, 4, ACCENT);
drawText("Walrus Memory + Tatum Sui Mainnet GraphQL", 84, 494, 3, INK, 1);
drawText("recallguard-oxunify.vercel.app", 84, 538, 4, SECONDARY, 1);

// PNG encode: signature + IHDR + IDAT + IEND
const crcTable = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (const byte of buf) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4);
ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
const raw = Buffer.alloc(H * (1 + W * 3));
for (let y = 0; y < H; y++) {
  raw[y * (1 + W * 3)] = 0;
  for (let x = 0; x < W * 3; x++) raw[y * (1 + W * 3) + 1 + x] = canvas[y * W * 3 + x];
}
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk("IHDR", ihdr),
  chunk("IDAT", deflateSync(raw, { level: 9 })),
  chunk("IEND", Buffer.alloc(0)),
]);

export function ogPng() {
  return png;
}

const IS_MAIN = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (IS_MAIN) {
  const outPath = resolve(dirname(fileURLToPath(import.meta.url)), "../site/og.png");
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, png);
  console.log(`wrote ${outPath} (${png.length} bytes, ${W}x${H})`);
}
